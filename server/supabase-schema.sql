create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  password_hash text not null,
  role text not null check (role in ('host','kitchen')),
  created_at timestamptz not null default now()
);
create table if not exists public.tables (
  id bigint generated by default as identity primary key,
  label text not null unique,
  capacity integer not null check (capacity > 0),
  state text not null default 'available' check (state in ('available','occupied','reserved'))
);
create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  price numeric(10,2) not null check (price >= 0),
  category text not null,
  available boolean not null default true
);
create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  email text not null,
  phone text,
  party_size integer not null check (party_size between 1 and 12),
  reserved_at timestamptz not null,
  table_id bigint references public.tables(id),
  status text not null default 'confirmed' check (status in ('confirmed','seated','cancelled','completed')),
  notes text,
  created_at timestamptz not null default now()
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  table_id bigint references public.tables(id),
  reservation_id bigint references public.reservations(id),
  guest_name text not null,
  status text not null default 'new' check (status in ('new','preparing','ready','served')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  menu_item_id bigint references public.menu_items(id),
  item_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0)
);
create table if not exists public.kitchen_events (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id),
  from_status text,
  to_status text not null check (to_status in ('new','preparing','ready','served')),
  user_id bigint references public.users(id),
  created_at timestamptz not null default now()
);
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id),
  action text not null,
  entity text not null,
  entity_id bigint,
  detail text,
  created_at timestamptz not null default now()
);

