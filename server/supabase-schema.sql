create or replace function public.create_reservation(
  p_customer_name text, p_email text, p_phone text, p_party_size integer,
  p_reserved_at timestamptz, p_notes text
) returns jsonb language plpgsql security definer set search_path = public as $$
declare chosen public.tables%rowtype; new_id bigint;
begin
  -- Serialize allocation so simultaneous requests cannot double-book a table.
  perform pg_advisory_xact_lock(250517);
  select t.* into chosen from public.tables t
  where t.capacity >= p_party_size and not exists (
    select 1 from public.reservations r where r.table_id=t.id
      and r.status in ('confirmed','seated')
      and abs(extract(epoch from (r.reserved_at-p_reserved_at))) < 7200
  ) order by t.capacity,t.label limit 1;
  if chosen.id is null then raise exception 'NO_TABLE_AVAILABLE'; end if;
  insert into public.reservations(customer_name,email,phone,party_size,reserved_at,table_id,notes)
  values(trim(p_customer_name),lower(trim(p_email)),coalesce(p_phone,''),p_party_size,p_reserved_at,chosen.id,coalesce(p_notes,''))
  returning id into new_id;
  insert into public.audit_logs(action,entity,entity_id,detail)
  values('create','reservation',new_id,'table '||chosen.label);
  return jsonb_build_object('id',new_id,'table',chosen.label,'status','confirmed');
end $$;

create or replace function public.create_order(
  p_table_id bigint, p_guest_name text, p_notes text, p_items jsonb, p_user_id bigint
) returns bigint language plpgsql security definer set search_path = public as $$
declare new_id bigint; item jsonb; dish public.menu_items%rowtype;
begin
  if not exists(select 1 from public.tables where id=p_table_id) then raise exception 'INVALID_TABLE'; end if;
  insert into public.orders(table_id,guest_name,notes) values(p_table_id,trim(p_guest_name),coalesce(p_notes,'')) returning id into new_id;
  for item in select * from jsonb_array_elements(p_items) loop
    select * into dish from public.menu_items where id=(item->>'menu_item_id')::bigint and available=true;
    if dish.id is null then raise exception 'MENU_ITEM_NOT_FOUND'; end if;
    insert into public.order_items(order_id,menu_item_id,item_name,quantity,unit_price)
    values(new_id,dish.id,dish.name,(item->>'quantity')::integer,dish.price);
  end loop;
  insert into public.kitchen_events(order_id,to_status,user_id) values(new_id,'new',p_user_id);
  insert into public.audit_logs(user_id,action,entity,entity_id,detail) values(p_user_id,'create','order',new_id,trim(p_guest_name));
  return new_id;
end $$;

create or replace function public.transition_order(
  p_order_id bigint, p_next_status text, p_user_id bigint
) returns void language plpgsql security definer set search_path = public as $$
declare current_status text; steps text[] := array['new','preparing','ready','served'];
begin
  select status into current_status from public.orders where id=p_order_id for update;
  if current_status is null then raise exception 'ORDER_NOT_FOUND'; end if;
  if array_position(steps,p_next_status) <> array_position(steps,current_status)+1 then raise exception 'INVALID_STATUS_TRANSITION'; end if;
  update public.orders set status=p_next_status,updated_at=now() where id=p_order_id;
  insert into public.kitchen_events(order_id,from_status,to_status,user_id) values(p_order_id,current_status,p_next_status,p_user_id);
  insert into public.audit_logs(user_id,action,entity,entity_id,detail) values(p_user_id,'status_change','order',p_order_id,current_status||' -> '||p_next_status);
end $$;

revoke all on function public.create_reservation(text,text,text,integer,timestamptz,text) from public, anon, authenticated;
revoke all on function public.create_order(bigint,text,text,jsonb,bigint) from public, anon, authenticated;
revoke all on function public.transition_order(bigint,text,bigint) from public, anon, authenticated;
grant execute on function public.create_reservation(text,text,text,integer,timestamptz,text) to service_role;
grant execute on function public.create_order(bigint,text,text,jsonb,bigint) to service_role;
grant execute on function public.transition_order(bigint,text,bigint) to service_role;

